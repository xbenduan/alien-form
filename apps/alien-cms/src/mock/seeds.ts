function daysAgo(days: number, hour: number, minute: number): number {
  const date = new Date();
  date.setDate(date.getDate() - days);
  date.setHours(hour, minute, 0, 0);
  return date.getTime();
}

function later(base: number, minutes: number): number {
  return base + minutes * 60 * 1000;
}

